import { deviceTextureFiles, textureFiles, textureMemoryBytes, type DeviceClass } from './textures';
import type { Finish } from './types';

/**
 * The asset manifest `apps/web/src/finishes/ASSETS.md`: every texture file with its source,
 * licence, size and SHA-256. `tools/finishes/fetch.mjs` writes it and a unit test of the web app
 * compares it with the files, so the text is made in one place.
 */

/** What is known of a file on disk, by its path under the textures folder. */
export type FileFacts = ReadonlyMap<string, { bytes: number; sha256: string }>;

const kb = (bytes: number) => `${(bytes / 1000).toFixed(1)} kB`;
const mb = (bytes: number) => `${(bytes / 1_000_000).toFixed(2)} MB`;

/** What a device downloads and holds for these finishes. */
export function deviceTotals(finishes: readonly Finish[], device: DeviceClass, files: FileFacts) {
  const fetched = finishes.flatMap((f) => deviceTextureFiles(f, device));
  return {
    files: fetched.length,
    download: fetched.reduce((sum, f) => sum + (files.get(f.path)?.bytes ?? 0), 0),
    memory: fetched.reduce((sum, f) => sum + textureMemoryBytes(f.size), 0),
  };
}

/** The manifest's text. A file missing from `files` is listed as missing, which fails the test. */
export function assetManifest(finishes: readonly Finish[], files: FileFacts): string {
  const textured = finishes.filter((f) => f.texture);
  const all = textured.flatMap(textureFiles);
  const lines = [
    '# Finish textures',
    '',
    '<!-- Generated by `pnpm finishes:manifest` (tools/finishes/fetch.mjs) from the finish definitions',
    '     in packages/shared/src/finishes/. Do not edit by hand. -->',
    '',
    'Every texture file of the finish library (`docs/home-model.md` § Finishes), with where it comes',
    'from. All of them are CC0 (public domain) textures from CC0 libraries. No texture is ever made',
    "from one of the owner's photos.",
    '',
    '| Device | Fetches | Files | Download | Memory on the GPU |',
    '| --- | --- | --- | --- | --- |',
    ...(['phone', 'desktop'] as const).map((device) => {
      const t = deviceTotals(textured, device, files);
      const what =
        device === 'phone' ? '512 px: colour, normal' : '1024 px: colour, normal, roughness';
      return `| ${device} | ${what} | ${t.files} | ${mb(t.download)} | ${mb(t.memory)} |`;
    }),
    '',
    `In the repository: ${all.length} files, ${mb(all.reduce((sum, f) => sum + (files.get(f.path)?.bytes ?? 0), 0))}.`,
    '',
  ];
  for (const finish of textured) {
    const source = finish.source!;
    lines.push(
      `## ${finish.id}`,
      '',
      `${finish.name}. Source: [${source.provider} · ${source.assetId}](${source.url}), licence ${source.licence}, fetched ${source.fetched}.` +
        ` One repeat covers ${finish.tileSize} m${source.crop === undefined ? '' : `, cut from ${source.crop * 100} % of the source's width`}.`,
      '',
      '| File | Size | SHA-256 |',
      '| --- | --- | --- |',
      ...textureFiles(finish).map((f) => {
        const facts = files.get(f.path);
        return `| \`${f.path}\` | ${facts ? kb(facts.bytes) : 'missing'} | ${facts ? `\`${facts.sha256}\`` : 'missing'} |`;
      }),
      '',
    );
  }
  return lines.join('\n');
}
